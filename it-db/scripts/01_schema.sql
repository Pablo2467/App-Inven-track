CREATE TABLE users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name     VARCHAR(150) NOT NULL,
  email         VARCHAR(150) NOT NULL,
  username      VARCHAR(60)  NOT NULL,
  password_hash VARCHAR(100) NOT NULL,
  role          VARCHAR(20)  NOT NULL,
  status        VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
  last_login_at TIMESTAMP(6) NULL,
  created_at    TIMESTAMP(6) NOT NULL,
  updated_at    TIMESTAMP(6) NOT NULL,
  CONSTRAINT uk_users_email    UNIQUE (email),
  CONSTRAINT uk_users_username UNIQUE (username),
  CONSTRAINT ck_users_role     CHECK (role   IN ('DUENO','EMPLEADA')),
  CONSTRAINT ck_users_status   CHECK (status IN ('ACTIVE','INACTIVE'))
);

CREATE TABLE suppliers (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR(150) NOT NULL,
  tax_id     VARCHAR(40)  NOT NULL,
  phone      VARCHAR(40)  NULL,
  email      VARCHAR(150) NULL,
  address    VARCHAR(255) NULL,
  status     VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT uk_suppliers_tax_id UNIQUE (tax_id),
  CONSTRAINT ck_suppliers_status CHECK (status IN ('ACTIVE','INACTIVE'))
);

CREATE TABLE products (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        VARCHAR(40)   NOT NULL,
  name        VARCHAR(150)  NOT NULL,
  description VARCHAR(500)  NULL,
  category    VARCHAR(100)  NULL,
  unit        VARCHAR(30)   NOT NULL,
  min_stock   DECIMAL(14,3) NOT NULL DEFAULT 0,
  status      VARCHAR(20)   NOT NULL DEFAULT 'ACTIVE',
  created_at  TIMESTAMP(6)  NOT NULL,
  updated_at  TIMESTAMP(6)  NOT NULL,
  CONSTRAINT uk_products_code      UNIQUE (code),
  CONSTRAINT ck_products_status    CHECK (status IN ('ACTIVE','INACTIVE')),
  CONSTRAINT ck_products_min_stock CHECK (min_stock >= 0)
);

CREATE TABLE lots (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lot_number         VARCHAR(80)   NOT NULL,
  product_id         BIGINT        NOT NULL,
  supplier_id        BIGINT        NOT NULL,
  initial_quantity   DECIMAL(14,3) NOT NULL,
  available_quantity DECIMAL(14,3) NOT NULL,
  entry_date         DATE          NOT NULL,
  expiration_date    DATE          NOT NULL,
  unit_cost          DECIMAL(14,2) NULL,
  status             VARCHAR(20)   NOT NULL DEFAULT 'AVAILABLE',
  created_at         TIMESTAMP(6)  NOT NULL,
  updated_at         TIMESTAMP(6)  NOT NULL,
  CONSTRAINT uk_lots_product_number UNIQUE (product_id, lot_number),
  CONSTRAINT fk_lots_product  FOREIGN KEY (product_id)  REFERENCES products (id),
  CONSTRAINT fk_lots_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (id),
  CONSTRAINT ck_lots_status    CHECK (status IN ('AVAILABLE','DEPLETED','EXPIRED')),
  CONSTRAINT ck_lots_initial   CHECK (initial_quantity > 0),
  CONSTRAINT ck_lots_available CHECK (available_quantity >= 0 AND available_quantity <= initial_quantity),
  CONSTRAINT ck_lots_dates     CHECK (expiration_date >= entry_date),
  CONSTRAINT ck_lots_cost      CHECK (unit_cost IS NULL OR unit_cost >= 0)
);

CREATE TABLE entries (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id  BIGINT        NOT NULL,
  supplier_id BIGINT        NOT NULL,
  lot_id      BIGINT        NOT NULL,
  quantity    DECIMAL(14,3) NOT NULL,
  entry_date  DATE          NOT NULL,
  user_id     BIGINT        NOT NULL,
  notes       VARCHAR(500)  NULL,
  created_at  TIMESTAMP(6)  NOT NULL,
  updated_at  TIMESTAMP(6)  NOT NULL,
  CONSTRAINT uk_entries_lot UNIQUE (lot_id),
  CONSTRAINT fk_entries_product  FOREIGN KEY (product_id)  REFERENCES products (id),
  CONSTRAINT fk_entries_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (id),
  CONSTRAINT fk_entries_lot      FOREIGN KEY (lot_id)      REFERENCES lots (id),
  CONSTRAINT fk_entries_user     FOREIGN KEY (user_id)     REFERENCES users (id),
  CONSTRAINT ck_entries_quantity CHECK (quantity > 0)
);

CREATE TABLE outputs (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT        NOT NULL,
  quantity   DECIMAL(14,3) NOT NULL,
  reason     VARCHAR(30)   NOT NULL,
  notes      VARCHAR(500)  NULL,
  exit_date  DATE          NOT NULL,
  user_id    BIGINT        NOT NULL,
  created_at TIMESTAMP(6)  NOT NULL,
  updated_at TIMESTAMP(6)  NOT NULL,
  CONSTRAINT fk_outputs_product FOREIGN KEY (product_id) REFERENCES products (id),
  CONSTRAINT fk_outputs_user    FOREIGN KEY (user_id)    REFERENCES users (id),
  CONSTRAINT ck_outputs_quantity CHECK (quantity > 0),
  CONSTRAINT ck_outputs_reason   CHECK (reason IN ('SALE','EXPIRED_DISPOSAL','DAMAGE','INTERNAL_USE','OTHER'))
);

CREATE TABLE inventory_movements (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  movement_type VARCHAR(10)   NOT NULL,
  product_id    BIGINT        NOT NULL,
  lot_id        BIGINT        NOT NULL,
  entry_id      BIGINT        NULL,
  output_id     BIGINT        NULL,
  quantity      DECIMAL(14,3) NOT NULL,
  user_id       BIGINT        NOT NULL,
  created_at    TIMESTAMP(6)  NOT NULL,
  updated_at    TIMESTAMP(6)  NOT NULL,
  CONSTRAINT fk_mov_product FOREIGN KEY (product_id) REFERENCES products (id),
  CONSTRAINT fk_mov_lot     FOREIGN KEY (lot_id)     REFERENCES lots (id),
  CONSTRAINT fk_mov_entry   FOREIGN KEY (entry_id)   REFERENCES entries (id),
  CONSTRAINT fk_mov_output  FOREIGN KEY (output_id)  REFERENCES outputs (id),
  CONSTRAINT fk_mov_user    FOREIGN KEY (user_id)    REFERENCES users (id),
  CONSTRAINT ck_mov_type     CHECK (movement_type IN ('ENTRY','EXIT')),
  CONSTRAINT ck_mov_quantity CHECK (quantity > 0)
);

-- Índices
CREATE INDEX idx_products_name     ON products (name);
CREATE INDEX idx_products_category ON products (category);
CREATE INDEX idx_suppliers_name    ON suppliers (name);
CREATE INDEX idx_lots_fifo         ON lots (product_id, entry_date, id);
CREATE INDEX idx_lots_expiration   ON lots (expiration_date);
CREATE INDEX idx_lots_supplier     ON lots (supplier_id);
CREATE INDEX idx_entries_date      ON entries (entry_date);
CREATE INDEX idx_outputs_date      ON outputs (exit_date);
CREATE INDEX idx_mov_product       ON inventory_movements (product_id);
CREATE INDEX idx_mov_created       ON inventory_movements (created_at);
CREATE INDEX idx_mov_user          ON inventory_movements (user_id);